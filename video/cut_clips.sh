#!/usr/bin/env bash
# Cuts the raw screen recording into the two footage scenes, time-stretched (setpts) to the exact
# scene length in src/Root.tsx (14 s each). Otherwise unedited: audio dropped (-an), 30 fps, a crop only.
# The crop removes the browser tab strip and bookmarks bar (private tabs); nothing is blurred or altered.
#
#   bash cut_clips.sh [recording.mp4]      # default: ../recordings/pending.mkv
#
# live   = recording 0:00-0:23  live mic order, bill, "Read the bill back"   -> 1.64x
# upload = recording 0:24-0:53  two of my own recordings uploaded, bills     -> 2.07x
set -euo pipefail
cd "$(dirname "$0")"
IN="${1:-../recordings/pending.mkv}"
CROP="${CROP:-1074:604:0:116}"   # w:h:x:y of the page area in the 1280x720 recording (below the browser chrome)
DUR=14
mkdir -p public/clips
cut() { # name start end
  local sp; sp=$(python -c "print(($3-$2)/$DUR)")
  echo "$1: ${2}s-${3}s -> ${DUR}s (speed ${sp}x)"
  ffmpeg -v error -y -ss "$2" -to "$3" -i "$IN" -an \
    -vf "crop=${CROP},setpts=PTS/${sp},fps=30,scale=1080:608" \
    -t "$DUR" -c:v libx264 -preset veryfast -crf 18 -pix_fmt yuv420p "public/clips/$1.mp4"
}
cut c1_live 0 23
cut c2_upload 24 53
cat > src/clips.ts <<'EOT'
// Generated by cut_clips.sh. true = public/clips/<name>.mp4 exists and is used instead of the still.
export const CLIPS: Record<string, boolean> = {
  c1_live: true,
  c2_upload: true,
};
EOT
echo "done"
